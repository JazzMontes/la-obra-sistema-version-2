  id            integer generated by default as identity primary key,
  name          varchar(100) not null,
  description   varchar(255) not null,
  category_id   integer not null references la_obra_v2.categories(id) on update cascade on delete restrict,
  type          varchar(10) not null check (type in ('prepared','resale')),
  price         numeric(10,2) not null,
