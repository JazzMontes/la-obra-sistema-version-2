create table if not exists la_obra_v2.users (
  id                    integer generated by default as identity primary key,
  name                  varchar(100) not null,
  username              varchar(50)  not null,
  email                 varchar(150) not null,
  password_hash         varchar(255) not null,
  status                varchar(10)  not null default 'pending'
                        check (status in ('pending','active','rejected','inactive')),
  role                  varchar(10)  null check (role in ('admin','employee')),
  must_change_password  boolean      not null default false,
  created_at            timestamp(0) not null default la_obra_v2.now_mx(),
  updated_at            timestamp(0) not null default la_obra_v2.now_mx()
);
-- MySQL comparaba sin distinguir mayúsculas; aquí se replica con índices sobre lower()
create unique index if not exists uq_users_username on la_obra_v2.users (lower(username));
create unique index if not exists uq_users_email    on la_obra_v2.users (lower(email));

create table if not exists la_obra_v2.sessions (
  id          integer generated by default as identity primary key,
  user_id     integer not null references la_obra_v2.users(id) on delete cascade,
  token_hash  varchar(255) not null unique,
  expires_at  timestamp(0) not null,
  created_at  timestamp(0) not null default la_obra_v2.now_mx()
);
create index if not exists idx_sessions_user on la_obra_v2.sessions(user_id);

-- updated_at automático (equivale a ON UPDATE CURRENT_TIMESTAMP de MySQL)
create or replace function la_obra_v2.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := la_obra_v2.now_mx();
  return new;
end $$;

drop trigger if exists trg_users_updated on la_obra_v2.users;
create trigger trg_users_updated before update on la_obra_v2.users
for each row execute function la_obra_v2.touch_updated_at();

