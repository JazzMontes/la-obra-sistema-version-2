-- ---------------------------------------------------------------------
-- ARCHIVOS (NUEVO EN LA VERSIÓN 2)
-- En XAMPP las fotos vivían en backend/uploads/. Aquí se guardan en la base
-- con la MISMA ruta (uploads/products/..., uploads/tickets/...), así la app
-- las pide igual que antes por files/image.php y solo las ve quien inició sesión.
-- Las fotos llegan comprimidas desde el teléfono (máx. 1024 px, JPEG).
-- ---------------------------------------------------------------------
create table if not exists la_obra_v2.files (
  path        varchar(255) primary key,
  mime        varchar(40)  not null,
  data        bytea        not null,
  size_bytes  integer      not null,
  created_at  timestamp(0) not null default la_obra_v2.now_mx()
);

