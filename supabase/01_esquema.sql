create table if not exists la_obra_v2.preparation_inputs (
  id              integer generated by default as identity primary key,
  preparation_id  integer not null references la_obra_v2.preparations(id) on delete cascade,
  input_id        integer not null references la_obra_v2.inputs(id) on delete restrict,
