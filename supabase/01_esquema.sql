-- =====================================================================
-- LA OBRA · SISTEMA VERSIÓN 2
-- 01 · Esquema de la base de datos (PostgreSQL / Supabase)
--
-- Es la conversión de la base MySQL "la_obra_db" (schema.sql + todas las
-- migraciones de la carpeta database/) a PostgreSQL.
--
-- Todo vive en el esquema propio "la_obra_v2", así que no se mezcla con
-- nada más del proyecto de Supabase ni con la versión 1 (XAMPP/MySQL).
-- Este esquema NO se publica en la API de Supabase: la app solo puede
-- entrar por la función pública la_obra_v2_api (archivo 04).
--
-- Se ejecuta UNA vez en el SQL Editor de Supabase (o usa instalar_todo.sql).
-- =====================================================================

create extension if not exists pgcrypto with schema extensions;

create schema if not exists la_obra_v2;

-- Hora del negocio. Supabase trabaja en UTC; el sistema guarda la hora
-- local de México igual que lo hacía PHP con America/Mexico_City.
create or replace function la_obra_v2.now_mx() returns timestamp(0)
language sql stable as $$
  select (now() at time zone 'America/Mexico_City')::timestamp(0)
$$;

create or replace function la_obra_v2.today_mx() returns date
language sql stable as $$
  select (now() at time zone 'America/Mexico_City')::date
$$;

