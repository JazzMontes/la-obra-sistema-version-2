-- Hora del negocio. Supabase trabaja en UTC; el sistema guarda la hora
-- local de México igual que lo hacía PHP con America/Mexico_City.
create or replace function la_obra_v2.now_mx() returns timestamp(0)
language sql stable as $$
  select (now() at time zone 'America/Mexico_City')::timestamp(0)
$$;

create or replace function la_obra_v2.today_mx() returns date
language sql stable as $$
  select (now() at time zone 'America/Mexico_City')::date
$$;

